function computeEfficiency(
  price_inr: number,
  carbs_g: number,
  sodium_mg: number,
  protein_g: number,
): Pick<FuelProduct, 'cost_per_25g_carb' | 'cost_per_500mg_sodium' | 'cost_per_20g_protein'> {
  return {
    cost_per_25g_carb: carbs_g > 0 ? Math.round((price_inr / carbs_g) * 25 * 100) / 100 : null,
    cost_per_500mg_sodium: sodium_mg > 0 ? Math.round((price_inr / sodium_mg) * 500 * 100) / 100 : null,
    cost_per_20g_protein: protein_g > 0 ? Math.round((price_inr / protein_g) * 20 * 100) / 100 : null,
  };
}

